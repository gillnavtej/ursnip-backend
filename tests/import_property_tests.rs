//! Property-based test for invalid import payloads (Property 5, task 5.3).
//!
//! Exercises the pure `ImportService::parse` function (no database required):
//! for ANY payload that is not valid JSON, or is valid JSON that does not match
//! the canonical import schema, `parse` SHALL reject the import with a parse
//! error (`AppError::ImportParseError`) AND produce zero candidate snippets —
//! nothing is ingested (Req 4.6).
//!
//! `ImportService::parse` is the sole gate before any ingestion: it either
//! returns `Ok(Vec<CandidateSnippet>)` (which task 5.2 then feeds to the batch
//! path) or `Err`. Ingestion is all-or-nothing at the parse boundary, so proving
//! that every invalid payload yields `Err` and no candidates is exactly the
//! "invalid payload ingests nothing" property — no live workspace is involved.
//!
//! Unlike the DB-backed suites in this repo, this test needs no database and is
//! NOT `#[ignore]`d: it runs as part of the normal `cargo test` suite.
//!
//! Requirements covered: 4.6

use proptest::prelude::*;
use proptest::test_runner::Config as ProptestConfig;

use ursnip_backend::errors::AppError;
use ursnip_backend::sync::import::ImportService;

// ─── Strategies ────────────────────────────────────────────────────────────────
//
// The design (Property 5) calls for four families of invalid payload:
//   * empty strings
//   * truncated JSON
//   * valid JSON of the wrong shape
//   * non-UTF-8-ish / malformed byte sequences
//
// Each family below is a `Strategy<Value = Vec<u8>>` so we can also cover the
// non-UTF-8 case (which is not expressible as a `String`). `ImportService::parse`
// accepts anything `AsRef<[u8]>`, so a byte vector is the common input type.

/// The canonical schema's valid `snippet_type` values are irrelevant here; what
/// matters is that every payload generated by the strategies below is *invalid*
/// — either not JSON at all, or JSON that does not match the strict
/// `deny_unknown_fields` schema `{ version, workspace_name?, snippets:[...] }`.

/// Family 1 — empty and whitespace-only payloads. An empty body is the simplest
/// invalid payload; whitespace-only is JSON-empty too.
fn empty_payload_strategy() -> impl Strategy<Value = Vec<u8>> {
    prop_oneof![
        Just(Vec::<u8>::new()),
        Just(b"".to_vec()),
        Just(b" ".to_vec()),
        Just(b"\n\t  \r\n".to_vec()),
    ]
}

/// Family 2 — truncated / structurally-malformed JSON. Take a well-formed
/// canonical document and cut it off at an arbitrary point (never the full
/// length), producing an unterminated / broken JSON token stream. Also mixes in
/// a few hand-written broken fragments.
fn truncated_json_strategy() -> impl Strategy<Value = Vec<u8>> {
    // A representative well-formed document to truncate.
    const FULL: &str = r#"{"version":1,"workspace_name":"ws","snippets":[{"trigger":"/hi","content":"hello world","snippet_type":"static","ai_prompt":null}]}"#;

    let truncated = (0usize..FULL.len()).prop_map(|cut| FULL.as_bytes()[..cut].to_vec());

    let hand_written = prop_oneof![
        Just(b"{ not json".to_vec()),
        Just(b"{\"version\":".to_vec()),
        Just(b"{\"version\":1,\"snippets\":[".to_vec()),
        Just(b"{\"snippets\":[{\"trigger\":\"/x\"".to_vec()),
        Just(b"[1,2,3".to_vec()),
        Just(b"}{".to_vec()),
        Just(b"\"unterminated".to_vec()),
    ];

    prop_oneof![truncated, hand_written]
}

/// Family 3 — valid JSON of the wrong shape. Each of these parses as JSON but
/// fails the strict canonical schema (missing required fields, wrong types,
/// unknown fields, or a non-object top level).
fn wrong_shape_json_strategy() -> impl Strategy<Value = Vec<u8>> {
    // Well-typed JSON values that are simply not the import document object.
    let scalars_and_arrays = prop_oneof![
        Just(b"null".to_vec()),
        Just(b"true".to_vec()),
        Just(b"false".to_vec()),
        Just(b"42".to_vec()),
        Just(b"3.14".to_vec()),
        Just(b"\"a string\"".to_vec()),
        Just(b"[]".to_vec()),
        Just(b"[{\"trigger\":\"/x\"}]".to_vec()),
        Just(b"{}".to_vec()),
    ];

    // Objects that are close to the schema but wrong: missing `version`, missing
    // `snippets`, wrong type for `snippets`, and per-snippet shape errors
    // (missing required field, wrong type, unknown field).
    let near_miss_objects = prop_oneof![
        Just(br#"{"snippets":[]}"#.to_vec()),                       // missing version
        Just(br#"{"version":1}"#.to_vec()),                         // missing snippets
        Just(br#"{"version":"1","snippets":[]}"#.to_vec()),        // version wrong type
        Just(br#"{"version":1,"snippets":"nope"}"#.to_vec()),      // snippets wrong type
        Just(br#"{"version":1,"snippets":{}}"#.to_vec()),          // snippets object not array
        Just(br#"{"version":1,"snippets":[{"trigger":"/x","snippet_type":"static"}]}"#.to_vec()), // snippet missing content
        Just(br#"{"version":1,"snippets":[{"content":"c","snippet_type":"static"}]}"#.to_vec()),  // snippet missing trigger
        Just(br#"{"version":1,"snippets":[{"trigger":"/x","content":"c"}]}"#.to_vec()),           // snippet missing snippet_type
        Just(br#"{"version":1,"snippets":[{"trigger":42,"content":"c","snippet_type":"static"}]}"#.to_vec()), // trigger wrong type
        Just(br#"{"version":1,"snippets":[{"trigger":"/x","content":"c","snippet_type":"static","bogus":true}]}"#.to_vec()), // unknown field on snippet
        Just(br#"{"version":1,"snippets":[],"bogus":true}"#.to_vec()), // unknown top-level field
    ];

    // Synthesize additional valid-JSON-wrong-shape documents: a valid object of
    // arbitrary string keys mapped to string values is JSON-valid but never
    // matches the strict schema (unknown fields / missing required ones).
    let arbitrary_object = prop::collection::vec(
        ("[a-z]{1,8}", "[a-zA-Z0-9 ]{0,12}"),
        0..4,
    )
    .prop_map(|pairs| {
        let body = pairs
            .into_iter()
            .map(|(k, v)| format!("{:?}:{:?}", k, v))
            .collect::<Vec<_>>()
            .join(",");
        format!("{{{body}}}").into_bytes()
    });

    prop_oneof![scalars_and_arrays, near_miss_objects, arbitrary_object]
}

/// Family 4 — non-UTF-8 / malformed byte sequences. These are not valid UTF-8,
/// so `serde_json` rejects them before any shape check. Includes standalone
/// invalid bytes and invalid bytes wrapped inside otherwise-JSON-looking
/// structure.
fn non_utf8_strategy() -> impl Strategy<Value = Vec<u8>> {
    // Bytes that are never valid on their own in UTF-8: 0x80–0xFF continuation /
    // invalid lead bytes, plus lone surrogate-ish and overlong-ish sequences.
    let raw_invalid = prop::collection::vec(0x80u8..=0xFF, 1..16);

    // Invalid bytes embedded where a JSON string would sit — the surrounding
    // braces make it "look" like a document, but the bytes break UTF-8 decoding.
    let embedded = prop::collection::vec(0x80u8..=0xFF, 1..8).prop_map(|mut junk| {
        let mut out = br#"{"version":1,"snippets":[{"trigger":"#.to_vec();
        out.push(b'"');
        out.append(&mut junk);
        out.extend_from_slice(br#""}]}"#);
        out
    });

    // A couple of fixed malformed sequences for good measure.
    let fixed = prop_oneof![
        Just(vec![0xFFu8, 0xFE, 0xFD]),
        Just(vec![0xC0u8, 0x80]),       // overlong encoding of NUL
        Just(vec![0xEDu8, 0xA0, 0x80]), // UTF-16 surrogate half
        Just(vec![b'{', 0xFF, b'}']),
    ];

    prop_oneof![raw_invalid, embedded, fixed]
        // Guard: on the vanishingly rare chance a generated byte vector *is* valid
        // UTF-8 AND valid schema JSON, map it to a definitively invalid payload so
        // the property's precondition ("payload is invalid") always holds.
        .prop_map(|bytes| {
            if ImportService::parse(&bytes).is_ok() {
                b"\xFF\xFE not utf-8".to_vec()
            } else {
                bytes
            }
        })
}

/// Any invalid import payload, drawn uniformly across the four required families.
fn invalid_payload_strategy() -> impl Strategy<Value = Vec<u8>> {
    prop_oneof![
        empty_payload_strategy(),
        truncated_json_strategy(),
        wrong_shape_json_strategy(),
        non_utf8_strategy(),
    ]
}

// ─── Property 5: Invalid import payload ingests nothing ─────────────────────────
//
// Feature: ursnip-feature-matrix, Property 5: Invalid import payload ingests nothing
//
// For any payload that is not valid JSON or does not conform to the expected
// snippet schema, the Import_Service SHALL reject the import with a parse error
// AND SHALL ingest zero snippets.
//
// `ImportService::parse` is the parse gate that precedes all ingestion (task 5.2
// only ingests the `Ok` candidates it returns). So for every invalid payload we
// assert BOTH halves of the requirement at the parse boundary:
//   1. parse returns `Err(AppError::ImportParseError)` (the descriptive parse
//      error, HTTP 422) — the import is rejected; and
//   2. parse yields NO candidate snippets — since it returned `Err`, there is no
//      `Vec<CandidateSnippet>` to hand to the batch path, so zero snippets are
//      ingested (Req 4.6).
//
// Generators cover the design's four required edge-case families: empty strings,
// truncated JSON, valid-JSON-wrong-shape, and non-UTF-8-ish byte sequences.
//
// **Validates: Requirements 4.6**

proptest! {
    #![proptest_config(ProptestConfig::with_cases(100))]

    #[test]
    fn prop_invalid_import_payload_ingests_nothing(payload in invalid_payload_strategy()) {
        let result = ImportService::parse(&payload);

        // Req 4.6, part 1: the import is rejected with the parse error. Any `Ok`
        // here would mean an invalid payload produced candidates that COULD be
        // ingested — a violation.
        match result {
            Err(AppError::ImportParseError) => {}
            Ok(candidates) => prop_assert!(
                false,
                "invalid payload {:?} must be rejected, but parse succeeded with {} \
                 candidate(s) (would ingest {} snippet(s))",
                String::from_utf8_lossy(&payload),
                candidates.len(),
                candidates.len(),
            ),
            Err(other) => prop_assert!(
                false,
                "invalid payload {:?} must be rejected with ImportParseError, got {:?}",
                String::from_utf8_lossy(&payload),
                other,
            ),
        }

        // Req 4.6, part 2: zero snippets are ingested. Because parse returned
        // `Err`, no candidate list exists to feed the batch path — the ingested
        // count is definitionally zero. Assert it explicitly for clarity.
        let ingested_count = ImportService::parse(&payload)
            .map(|candidates| candidates.len())
            .unwrap_or(0);
        prop_assert_eq!(
            ingested_count,
            0,
            "an invalid payload must ingest zero snippets, ingested {}",
            ingested_count,
        );
    }
}
